def build_profile(attrs: dict, scenario: str = "common") -> str:
    prompt = PROMPTS.get(scenario, PROMPTS["common"])
    resp = client.chat.completions.create(
        model="deepseek-chat",       # быстрее/дешевле, хватит 400 токенов
        messages=[
            {"role": "system", "content": prompt},
            {"role": "user", "content": json.dumps(attrs, ensure_ascii=False)},
        ],
        max_tokens=1000,
        temperature=0.75,
    )
    return resp.choices[0].message.content.strip()
